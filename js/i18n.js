function t(lang, key) {
  return (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
}

const loadedFonts = new Set();
function loadFont(lang) {
  const font = (LANGS[lang] || LANGS.en).font;
  if (loadedFonts.has(font)) return;
  loadedFonts.add(font);
  const link = document.createElement("link");
  link.rel = "stylesheet";
  link.href = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(font).replace(/%20/g, "+")}:wght@400;600;700&display=swap`;
  document.head.appendChild(link);
}

/* Apply translations to elements with data-i18n="key" inside root. */
function applyI18n(lang, root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(lang, el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(lang, el.dataset.i18nPh); });
}

function setPageLang(lang) {
  const meta = LANGS[lang] || LANGS.en;
  document.documentElement.lang = lang;
  document.documentElement.dir = meta.dir;
  document.documentElement.style.setProperty("--script-font", `"${meta.font}"`);
  loadFont(lang);
}

function fillLangSelect(select, current) {
  select.innerHTML = Object.entries(LANGS)
    .map(([code, m]) => `<option value="${code}"${code === current ? " selected" : ""}>${m.name}</option>`)
    .join("");
}

function preferredLang() {
  try {
    const saved = localStorage.getItem("ui-lang");
    if (saved && LANGS[saved]) return saved;
  } catch (_) { /* storage unavailable */ }
  const nav = (navigator.language || "en").slice(0, 2);
  return LANGS[nav] ? nav : "en";
}

function rememberLang(lang) {
  try { localStorage.setItem("ui-lang", lang); } catch (_) { /* ignore */ }
}
