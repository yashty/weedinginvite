function t(lang, key) {
  return (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
}

const loadedFonts = new Set();
function loadFont(lang) {
  const font = (LANGS[lang] || LANGS.en).font;
  if (loadedFonts.has(font)) return;
  loadedFonts.add(font);
  const link = document.createElement("link");
  link.rel = "stylesheet";
  link.href = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(font).replace(/%20/g, "+")}:wght@400;600;700&display=swap`;
  document.head.appendChild(link);
}

/* Apply translations to elements with data-i18n="key" inside root. */
function applyI18n(lang, root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(lang, el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(lang, el.dataset.i18nPh); });
}

